#!/bin/bash
# Applies the wallpaper given as the first argument (the Quickshell wallpaper picker runs this).
# The palette is made first (everything else reads it); then everything that uses it is updated in
# parallel. Quickshell picks the new colors up by itself (it watches the wal files).
#
#   wallpaper.sh <image>                 set the wallpaper and theme everything from it
#   wallpaper.sh --plain '#RRGGBB' [keep]   set a plain-color wallpaper (made once in ~/wallpapers/plain);
#                                        the two blacks (000000, 1C1C1E) also set the swatch back to auto,
#                                        unless `keep` (the picker's black wallpapers whose colors follow
#                                        the swatch)
#   wallpaper.sh --swatch auto|'#A'|'#A,#B'   theme from one or two colors instead of the wallpaper
#                                        (kept across wallpaper changes until set back to auto)
#   wallpaper.sh --harmony monochrome|complementary|split|analogous|triadic
#                                        how a one-color swatch is grown into a palette (a plain
#                                        wallpaper is always shades of its own color)
# The swatch and harmony are kept in ~/.cache/wal-swatch.json (the picker shows them from there).
STATE="$HOME/.cache/wal-swatch.json"
PLAIN_DIR="$HOME/wallpapers/plain"

swatch() { [ -f "$STATE" ] && jq -r '.swatch | join(" ")' "$STATE"; }
harmony() { { [ -f "$STATE" ] && jq -r '.harmony // empty' "$STATE"; } || true; }
save_state() {   # $1: colors, space-separated ("" = follow the wallpaper), $2: harmony
    jq -n --arg s "$1" --arg h "${2:-analogous}" '{swatch: ($s | split(" ") | map(select(. != ""))), harmony: $h}' \
        > "$STATE.tmp" && mv "$STATE.tmp" "$STATE"
}
current_wallpaper() { jq -r .wallpaper ~/.cache/wal/colors.json; }   # wpaperctl only knows the copy at boot

# The palette for a wallpaper: the swatch's while one is set, a plain wallpaper's own color, or the
# wallpaper's hand-tuned scheme (generated by ~/.config/wal/gen_schemes.py); pywal's own extraction
# for wallpapers without one.
apply_palette() {
    local wallpaper="$1" colors h scheme
    colors=$(swatch)
    h=$(harmony)
    if [ -z "$colors" ] && [[ "$wallpaper" == "$PLAIN_DIR"/* ]]; then
        colors="#$(basename "$wallpaper" .png)"
        h=monochrome
    fi
    if [ -n "$colors" ]; then
        scheme="$HOME/.cache/wal/swatch-scheme.json"
        # shellcheck disable=SC2086   # one or two colors
        python3 ~/.config/wal/swatch_scheme.py "$scheme" "$wallpaper" "${h:-analogous}" $colors
        wal --theme "$scheme" -n -s
    else
        scheme="$HOME/.config/wal/wallpaper-schemes/$(basename "$wallpaper").json"
        # New image without a palette yet: generate it once (takes about a second)
        [ -f "$scheme" ] || python3 ~/.config/wal/gen_schemes.py "$wallpaper" >/dev/null 2>&1
        if [ -f "$scheme" ]; then
            wal --theme "$scheme" -n -s
        else
            wal -i "$wallpaper" -n -s
        fi
    fi

    # Everything that uses the palette, in parallel

    {   # Saturated dark gradient ends for the Quickshell bar, then kitty's background gradient (which
        # uses them) and its colors; make running kitty windows reload the theme
        ~/.config/quickshell/scripts/bar-colors.py
        ~/.config/kitty/gradient.py
        cat ~/.cache/wal/colors-kitty.conf > ~/.config/kitty/current-theme.conf
        pkill -USR1 kitty
    } &

    {   # Hyprland's border colors (and the scratchpads' border rule, by name), without reloading its
        # whole config: a reload stutters and resets changes made at runtime
        local active inactive
        active=$(sed -n 's/^\s*\$color1 = //p' ~/.cache/wal/colors-hyprland)
        inactive=$(sed -n 's/^\s*\$color2 = //p' ~/.cache/wal/colors-hyprland)
        hyprctl eval "hl.config({ general = { col = { active_border = \"$active\", inactive_border = \"$inactive\" } } })"
        hyprctl eval "hl.window_rule({ name = \"scratchpad-border\", match = { class = \"^kitty-.*\$\" }, border_color = \"$active $inactive\" })"
    } >/dev/null &

    swaync-client --reload-css &
    pywalfox update &

    wait
}

set_wallpaper() {
    local selected_wallpaper="$1"
    [ -f "$selected_wallpaper" ] || { echo "usage: $0 <wallpaper image>" >&2; exit 1; }

    # Stop any live wallpaper (a plain kill leaves players that failed to load a link running)
    pkill -9 -x mpvpaper

    # Apply wallpaper (wpaperd runs the transition on the GPU; see wpaperd.toml)
    wpaperctl set "$selected_wallpaper"

    # Save the current wallpaper path (in the background, while the palette is applied)
    cp "$selected_wallpaper" ~/wallpapers/pywallpaper.jpg &

    apply_palette "$selected_wallpaper"
    wait
}

case "$1" in
    --plain)
        hex=$(tr -d '#' <<< "$2" | tr 'a-f' 'A-F')
        [[ "$hex" =~ ^[0-9A-F]{6}$ ]] || { echo "usage: $0 --plain '#RRGGBB'" >&2; exit 1; }
        mkdir -p "$PLAIN_DIR"
        [ -f "$PLAIN_DIR/$hex.png" ] ||
            python3 -c "import sys; from PIL import Image; Image.new('RGB', (3840, 2160), '#' + sys.argv[1]).save(sys.argv[2])" \
                "$hex" "$PLAIN_DIR/$hex.png"
        # the OLED and matte black wallpapers theme everything black: a swatch would color it instead
        [[ "$3" != keep && ( "$hex" == 000000 || "$hex" == 1C1C1E ) ]] && save_state "" "$(harmony)"
        set_wallpaper "$PLAIN_DIR/$hex.png"
        ;;
    --swatch)
        colors=$([ "$2" = auto ] || tr ',' ' ' <<< "$2")
        save_state "$colors" "$(harmony)"
        apply_palette "$(current_wallpaper)"
        ;;
    --harmony)
        save_state "$(swatch)" "$2"
        apply_palette "$(current_wallpaper)"
        ;;
    *)
        set_wallpaper "$1"
        ;;
esac
