#!/bin/bash
# Applies the wallpaper given as the first argument (the Quickshell wallpaper picker runs this).
# The palette is made first (everything else reads it); then everything that uses it is updated in
# parallel. Quickshell picks the new colors up by itself (it watches the wal files).
main() {
    selected_wallpaper="$1"
    [ -f "$selected_wallpaper" ] || { echo "usage: $0 <wallpaper image>" >&2; exit 1; }

    # 0. Stop any live wallpaper (a plain kill leaves players that failed to load a link running)
    pkill -9 -x mpvpaper

    # 1. Apply wallpaper (swww runs the transition in the background)
    swww img "$selected_wallpaper" --transition-type any --resize crop --transition-fps 144 --transition-duration 1.5

    # 2. Apply the hand-tuned per-wallpaper palette (generated by ~/.config/wal/gen_schemes.py);
    #    fall back to pywal's own extraction for wallpapers without one.
    scheme="$HOME/.config/wal/wallpaper-schemes/$(basename "$selected_wallpaper").json"
    # New image without a palette yet: generate it once (takes about a second)
    [ -f "$scheme" ] || python3 ~/.config/wal/gen_schemes.py "$selected_wallpaper" >/dev/null 2>&1
    if [ -f "$scheme" ]; then
        wal --theme "$scheme" -n -s
    else
        wal -i "$selected_wallpaper" -n -s
    fi

    # $wallpaper, $color1, $color2, ... of the new palette
    source ~/.cache/wal/colors.sh

    # 3. Everything that uses the palette, in parallel

    {   # Saturated dark gradient ends for the Quickshell bar, then kitty's background gradient (which
        # uses them) and its colors; make running kitty windows reload the theme
        ~/.config/quickshell/scripts/bar-colors.py
        ~/.config/kitty/gradient.py
        cat ~/.cache/wal/colors-kitty.conf > ~/.config/kitty/current-theme.conf
        pkill -USR1 kitty
    } &

    {   # Hyprland's border colors (and the scratchpads' border rule, by name), without reloading its
        # whole config: a reload stutters and resets changes made at runtime
        local active inactive
        active=$(sed -n 's/^\s*\$color1 = //p' ~/.cache/wal/colors-hyprland)
        inactive=$(sed -n 's/^\s*\$color2 = //p' ~/.cache/wal/colors-hyprland)
        hyprctl eval "hl.config({ general = { col = { active_border = \"$active\", inactive_border = \"$inactive\" } } })"
        hyprctl eval "hl.window_rule({ name = \"scratchpad-border\", match = { class = \"^kitty-.*\$\" }, border_color = \"$active $inactive\" })"
    } >/dev/null &

    swaync-client --reload-css &
    pywalfox update &

    # Save the current wallpaper path
    cp "$wallpaper" ~/wallpapers/pywallpaper.jpg &

    wait
}

main "$@"
