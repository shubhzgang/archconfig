#!/bin/bash
WALLPAPER_DIR="$HOME/wallpapers/walls"
# Photo 2x the 196x130 size it is shown at (center-cropped to the wallpaper picker card shape
# so the card margin is even on all sides), so it stays sharp, plus a 12px margin for the shadow
THUMB_DIR="$HOME/.cache/hypr-wallpaper-thumbs-416x284"
THUMB_W=392
THUMB_H=260

THUMB_MASK="$HOME/.cache/wal/rofi-thumb-mask.png"
THUMB_SHADOW="$HOME/.cache/wal/rofi-thumb-shadow.png"

export WALLPAPER_DIR THUMB_DIR THUMB_W THUMB_H THUMB_MASK THUMB_SHADOW

make_thumb() {
    local file="$1"
    local rel="${file#"$WALLPAPER_DIR"/}"
    local thumb="$THUMB_DIR/$rel.png"
    mkdir -p "$(dirname "$thumb")"
    if [ -f "$thumb" ] && [ "$thumb" -nt "$file" ]; then
        return
    fi
    # Crop to size, round the corners (mask) and set the photo on its soft shadow, both
    # rendered by rofi/make-cards.py; without them fall back to a plain thumbnail.
    if [ -f "$THUMB_MASK" ] && [ -f "$THUMB_SHADOW" ]; then
        magick "$THUMB_SHADOW" \( "${file}[0]" -resize "${THUMB_W}x${THUMB_H}^" -gravity center -extent "${THUMB_W}x${THUMB_H}" \
            "$THUMB_MASK" -alpha off -compose CopyOpacity -composite \) \
            -gravity center -compose over -composite "$thumb" 2>/dev/null
    else
        magick "${file}[0]" -resize "${THUMB_W}x${THUMB_H}^" -gravity center -extent "${THUMB_W}x${THUMB_H}" -quality 80 "$thumb" 2>/dev/null
    fi
}
export -f make_thumb

menu() {
    local files=()
    while IFS= read -r -d '' f; do files+=("$f"); done < <(
        find "${WALLPAPER_DIR}" -type f \( -iname "*.jpg" -o -iname "*.jpeg" -o -iname "*.png" -o -iname "*.gif" \) -print0
    )
    printf '%s\0' "${files[@]}" | xargs -0 -P "$(nproc)" -n1 bash -c 'make_thumb "$@"' _
    local f
    for f in "${files[@]}"; do
        rel="${f#"$WALLPAPER_DIR"/}"
        printf '%s\0icon\x1f%s\n' "$rel" "$THUMB_DIR/$rel.png"
    done
}

main() {
    # thumbnail shading assets (fresh checkout): render them before thumbnails are made
    [ -f "$THUMB_MASK" ] || ~/.config/rofi/make-cards.py

    choice=$(menu | rofi -dmenu -show-icons -theme ~/.config/rofi/wallpaper.rasi -p "Select Wallpaper")
    
    # SAFETY CHECK: Exit the script immediately if you hit escape or close rofi without picking anything
    if [ -z "$choice" ]; then
        exit 0
    fi

    selected_wallpaper="$WALLPAPER_DIR/$choice"
    
    # 1. Apply wallpaper
    swww img "$selected_wallpaper" --transition-type any --resize crop --transition-fps 144 --transition-duration 1.5
    
    # 2. Apply the hand-tuned per-wallpaper palette (generated by ~/.config/wal/gen_schemes.py);
    #    fall back to pywal's own extraction for wallpapers without one.
    scheme="$HOME/.config/wal/wallpaper-schemes/$(basename "$selected_wallpaper").json"
    # New image without a palette yet: generate it once (takes about a second)
    [ -f "$scheme" ] || python3 ~/.config/wal/gen_schemes.py "$selected_wallpaper" >/dev/null 2>&1
    if [ -f "$scheme" ]; then
        wal --theme "$scheme" -n -s
    else
        wal -i "$selected_wallpaper" -n -s
    fi
    
    # Saturated dark gradient ends for the Quickshell bar sections (also used by rofi and kitty)
    ~/.config/quickshell/scripts/bar-colors.py
    ~/.config/kitty/gradient.py  # kitty's background gradient uses the same colors
    ~/.config/rofi/make-cards.py  # rofi card images (selected card uses the new color1)

    # Hyprland reads the border colors from the pywal file only at config load
    hyprctl reload

    # 3. Source the generated colors
    # By sourcing this file directly, you instantly load $wallpaper, $color1, $color2, etc. as variables, removing the need for complex awk commands.
    source ~/.cache/wal/colors.sh
    
    # 4. Update basic UI elements
    swaync-client --reload-css
    cat ~/.cache/wal/colors-kitty.conf > ~/.config/kitty/current-theme.conf
    pkill -USR1 kitty  # make running kitty windows reload the theme
    pywalfox update
    
    # 5. Update Cava (Using the sourced $color2 and $color3 variables)
    cava_config="$HOME/.config/cava/config"
    sed -i "s/^gradient_color_1 = .*/gradient_color_1 = '$color2'/" "$cava_config"
    sed -i "s/^gradient_color_2 = .*/gradient_color_2 = '$color3'/" "$cava_config"
    pkill -USR2 cava 2>/dev/null
    
    # 6. Update OpenRGB
    # Instead of reading the 5th line of a file, we can just strip the '#' from the $color5 variable
    sys_box_color=$(echo "$color5" | sed 's/#//')
    echo "$sys_box_color"
    saturated_color=$(python ~/.config/hypr/inc_saturation.py "$sys_box_color" "2.0")
    echo "$saturated_color"
    
    # Added quotes around variables to prevent shell expansion errors
    ~/Downloads/OpenRGB_1.0rc1_x86_64_1fbacde.AppImage -c "$saturated_color"
    
    # 7. Save current wallpaper path
    cp -r "$wallpaper" ~/wallpapers/pywallpaper.jpg 
}

main
